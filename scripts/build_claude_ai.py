APP_NOTE = ("> **Claude app note:** this file comes from the Hack Kit plugin. `.hackathon/<FILE>.md` means that section of "
            "the Idea Pack (or a real file if this session has file tools). Templates are in `templates/`. Where it says to "
            "launch subagents, simulate them one after another in this chat and say so. The plugin's Python scripts aren't "
            "included here: when a step says to run one, apply the same rules by hand.\n\n")


def adapt(text):
    """Make plugin text work inside the Claude app skill folder."""
    text = re.sub(r"\A---\n.*?\n---\n+", "", text, flags=re.S)  # drop plugin frontmatter
    text = text.replace("${CLAUDE_PLUGIN_ROOT}/templates/", "templates/")
    text = text.replace("${CLAUDE_PLUGIN_ROOT}/skills/hack-court/SKILL.md", "court.md")
    text = text.replace("${CLAUDE_PLUGIN_ROOT}/skills/hack-court/jurors.json", "jurors.json")
    text = text.replace("${CLAUDE_PLUGIN_ROOT}/skills/hack-kit/SKILL.md", "SKILL.md")
    text = text.replace("${CLAUDE_PLUGIN_ROOT}/scripts/", "<plugin>/scripts/")
    text = text.replace("Arguments: $ARGUMENTS\n\n", "")
    return text


def files():
    """All files of the generated skill, as {relative path: text}."""
    out = {"SKILL.md": build()}
    for f in sorted((ROOT / "commands").glob("*.md")):
        out[f"phases/{f.name}"] = APP_NOTE + adapt(f.read_text(encoding="utf-8"))
    for f in sorted((ROOT / "templates").glob("*.md")):
        out[f"templates/{f.name}"] = f.read_text(encoding="utf-8")
    out["court.md"] = APP_NOTE + adapt((ROOT / "skills" / "hack-court" / "SKILL.md").read_text(encoding="utf-8"))
    out["jurors.json"] = (ROOT / "skills" / "hack-court" / "jurors.json").read_text(encoding="utf-8")
    return out


def zip_bytes(fileset):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for rel in sorted(fileset):
            info = zipfile.ZipInfo(f"hack-kit/{rel}", date_time=FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, fileset[rel])
    return buf.getvalue()


def zip_contents(data):
    """Files inside a zip as {relative path: text}. Compared by content, since compressed bytes vary by zlib version."""
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        return {n[len("hack-kit/"):]: z.read(n).decode("utf-8") for n in z.namelist()
                if n.startswith("hack-kit/") and not n.endswith("/")}


def main():
    fileset = files()
    data = zip_bytes(fileset)
    if "--check" in sys.argv:
        on_disk = {str(p.relative_to(SKILL_DIR)): p.read_text(encoding="utf-8")
                   for p in SKILL_DIR.rglob("*") if p.is_file()} if SKILL_DIR.exists() else {}
        ok = on_disk == fileset and ZIP.exists() and zip_contents(ZIP.read_bytes()) == fileset
        print("claude.ai skill is up to date" if ok else "claude.ai skill is OUT OF DATE: run python3 scripts/build_claude_ai.py")
        sys.exit(0 if ok else 1)
    for old in SKILL_DIR.rglob("*") if SKILL_DIR.exists() else []:
        if old.is_file() and str(old.relative_to(SKILL_DIR)) not in fileset:
            old.unlink()
    for rel, text in fileset.items():
        dest = SKILL_DIR / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text, encoding="utf-8")
    ZIP.parent.mkdir(parents=True, exist_ok=True)
    ZIP.write_bytes(data)
    print(f"Wrote {len(fileset)} files to {SKILL_DIR.relative_to(ROOT)}/ and {ZIP.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
